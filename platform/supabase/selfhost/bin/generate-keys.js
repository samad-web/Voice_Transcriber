#!/usr/bin/env node
/**
 * Generate every secret the self-hosted Supabase stack needs.
 *
 *   node bin/generate-keys.js                      # print to stdout
 *   node bin/generate-keys.js --write .env.selfhost   # fill the blanks in place
 *   node bin/generate-keys.js --write .env.selfhost --force   # ROTATE everything
 *
 * Without --force this only ever fills variables that are MISSING OR EMPTY. A
 * second run is therefore safe: it will not silently rotate the JWT secret of a
 * running stack and sign every user out, which is what an unconditional
 * regenerate-and-overwrite would do.
 *
 * ── ANON_KEY AND SERVICE_ROLE_KEY ARE DERIVED, NOT RANDOM ────────────────────
 *
 * Both are HS256 JWTs signed with JWT_SECRET, carrying {"role":"anon"} and
 * {"role":"service_role"}. Every Supabase service verifies them against that
 * same secret, so the three values are one unit: change JWT_SECRET and both
 * keys must be reissued together, or the gateway rejects everything.
 *
 * That is also why --force is all-or-nothing. Rotating JWT_SECRET while keeping
 * the old ANON_KEY produces a stack that starts cleanly and 401s every request.
 *
 * Node's crypto only - this runs on the VPS with no install step.
 */
"use strict";

const crypto = require("node:crypto");
const fs = require("node:fs");

/**
 * Alphanumeric on purpose, with no symbols.
 *
 * POSTGRES_PASSWORD ends up inside DATABASE_URL in .env.production, where a raw
 * `@` splits the URL at the wrong place and a `$` is eaten by compose's own
 * ${VAR} substitution. Percent-encoding is the documented fix and it is
 * routinely forgotten - see the 2026-08-31 outage. Sidestep it entirely.
 *
 * 62 symbols, so ~5.95 bits per character: 40 chars is ~238 bits.
 */
function token(length) {
  const alphabet = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789";
  const out = [];
  // Rejection sampling: 256 % 62 != 0, so a plain modulo would bias the first
  // 8 letters upward. Cheap to do correctly.
  const limit = 256 - (256 % alphabet.length);
  while (out.length < length) {
    for (const byte of crypto.randomBytes(length * 2)) {
      if (byte >= limit) continue;
      out.push(alphabet[byte % alphabet.length]);
      if (out.length === length) break;
    }
  }
  return out.join("");
}

const b64url = (buf) => Buffer.from(buf).toString("base64url");

/** An HS256 JWT, matching the shape Supabase's own keys use. */
function signJwt(payload, secret) {
  const header = b64url(JSON.stringify({ alg: "HS256", typ: "JWT" }));
  const body = b64url(JSON.stringify(payload));
  const signature = crypto
    .createHmac("sha256", secret)
    .update(`${header}.${body}`)
    .digest("base64url");
  return `${header}.${body}.${signature}`;
}

/**
 * Ten years. These are infrastructure keys, not user sessions - an expiry short
 * enough to be a security control would instead be an outage nobody diarised,
 * because the symptom is every request 401ing at once with no deploy to blame.
 */
const TEN_YEARS_SECONDS = 10 * 365 * 24 * 60 * 60;

function generate() {
  const jwtSecret = token(48);
  const issuedAt = Math.floor(Date.now() / 1000);
  const expiresAt = issuedAt + TEN_YEARS_SECONDS;
  const claims = (role) => ({ role, iss: "supabase", iat: issuedAt, exp: expiresAt });

  return {
    POSTGRES_PASSWORD: token(40),
    JWT_SECRET: jwtSecret,
    ANON_KEY: signJwt(claims("anon"), jwtSecret),
    SERVICE_ROLE_KEY: signJwt(claims("service_role"), jwtSecret),
    DASHBOARD_PASSWORD: token(32),
    // Fixed lengths the services actually require - not stylistic.
    SECRET_KEY_BASE: token(64),
    VAULT_ENC_KEY: token(32),
    PG_META_CRYPTO_KEY: token(32),
    REALTIME_DB_ENC_KEY: token(32),
    S3_PROTOCOL_ACCESS_KEY_ID: crypto.randomBytes(16).toString("hex"),
    S3_PROTOCOL_ACCESS_KEY_SECRET: crypto.randomBytes(32).toString("hex"),
    _expiresAt: expiresAt,
  };
}

/** Values of KEY=VALUE lines, ignoring comments. Good enough for a .env file. */
function readEnv(text) {
  const found = new Map();
  for (const line of text.split(/\r?\n/)) {
    const match = /^\s*([A-Z0-9_]+)\s*=(.*)$/.exec(line);
    if (match) found.set(match[1], match[2].trim());
  }
  return found;
}

function main() {
  const args = process.argv.slice(2);
  const force = args.includes("--force");
  const writeIndex = args.indexOf("--write");
  const target = writeIndex === -1 ? null : args[writeIndex + 1];

  if (writeIndex !== -1 && !target) {
    console.error("--write needs a file path, e.g. --write .env.selfhost");
    process.exit(1);
  }

  const generated = generate();
  const expiresAt = generated._expiresAt;
  delete generated._expiresAt;

  if (!target) {
    console.log("# Generated by bin/generate-keys.js on " + new Date().toISOString());
    console.log("# ANON_KEY / SERVICE_ROLE_KEY expire " + new Date(expiresAt * 1000).toISOString());
    for (const [key, value] of Object.entries(generated)) console.log(`${key}=${value}`);
    return;
  }

  if (!fs.existsSync(target)) {
    console.error(`${target} does not exist. Copy .env.selfhost.example to it first.`);
    process.exit(1);
  }

  const original = fs.readFileSync(target, "utf8");
  const existing = readEnv(original);

  // Which keys already hold a real value? Those are the ones a re-run must not
  // touch, because something may already be authenticating with them.
  const populated = Object.keys(generated).filter((k) => (existing.get(k) ?? "") !== "");

  if (populated.length && !force) {
    console.error(
      [
        `Refusing to overwrite ${populated.length} secret(s) already set in ${target}:`,
        ...populated.map((k) => `  ${k}`),
        "",
        "Filling only the empty ones. If you genuinely want to ROTATE these, re-run",
        "with --force - and understand what that costs:",
        "",
        "  JWT_SECRET      every console session is invalidated; everyone signs in again",
        "  ANON_KEY        NEXT_PUBLIC_SUPABASE_ANON_KEY is a BUILD ARG - the web image",
        "                  must be rebuilt, not restarted, or sign-in breaks",
        "  POSTGRES_PASSWORD  baked into the data directory at init; changing it here",
        "                  alone does NOT change it in the database (see utils/db-passwd.sh)",
        "",
      ].join("\n"),
    );
  }

  let updated = original;
  const filled = [];
  const skipped = [];

  for (const [key, value] of Object.entries(generated)) {
    const isSet = (existing.get(key) ?? "") !== "";
    if (isSet && !force) {
      skipped.push(key);
      continue;
    }
    const pattern = new RegExp(`^\\s*${key}\\s*=.*$`, "m");
    updated = pattern.test(updated)
      ? updated.replace(pattern, `${key}=${value}`)
      : `${updated.replace(/\s*$/, "")}\n${key}=${value}\n`;
    filled.push(key);
  }

  // 0600 up front: the file holds the database superuser password and a
  // service-role key that bypasses RLS on every tenant.
  fs.writeFileSync(target, updated, { mode: 0o600 });
  try {
    fs.chmodSync(target, 0o600);
  } catch {
    // Windows has no POSIX mode. Harmless here - this file is meant to be
    // filled in on the VPS, and the runbook says chmod 600 there.
  }

  console.log(`${target}: ${filled.length} secret(s) written${filled.length ? ":" : "."}`);
  for (const key of filled) console.log(`  + ${key}`);
  if (skipped.length) {
    console.log(`${skipped.length} left untouched (already set): ${skipped.join(", ")}`);
  }
  if (filled.includes("ANON_KEY")) {
    console.log("");
    console.log("ANON_KEY / SERVICE_ROLE_KEY expire " + new Date(expiresAt * 1000).toISOString());
    console.log("Copy ANON_KEY and SERVICE_ROLE_KEY into platform/.env.production as");
    console.log("NEXT_PUBLIC_SUPABASE_ANON_KEY and SUPABASE_SERVICE_ROLE_KEY, then REBUILD");
    console.log("the web image - the anon key is a build arg, so a restart will not take.");
  }
}

main();
